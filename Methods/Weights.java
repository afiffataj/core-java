class Weights {
    public static void main(String[] args) {

        System.out.println("The weights");

        float a = 10.5f;
        float b = 20.5f;

        Weights.display(a, b);
    }

    static float display(float a, float b) {
        System.out.println(a);
        System.out.println(b);
        return a;
    }
}