class Laptop{
	public static void main(String[] args){
        
        int a = 678;
        int b = 60;
        
        int sum = a + b;
        System.out.println(sum);  // Addition
        
        int sum1 = a - b;
        System.out.println(sum1); // Subtraction
        
        int sum2 = a * b;
        System.out.println(sum2); // Multiplication
        
        int sum3 = a / b;
        System.out.println(sum3); // Division
        
        boolean sum4 = (a == b);
        System.out.println(sum4); // Equal check
        
        int sum5 = a % b; // Modulus
        System.out.println(sum5);
        
        boolean sum6 = (a > b);
        System.out.println(sum6); // Greater than check
        
        boolean sum7 = (a < b);
        System.out.println(sum7); // Less than check
        
        boolean sum8 = (a <= b);
        System.out.println(sum8); // Less than or equal
        
        boolean sum9 = (a >= b);
        System.out.println(sum9); // Greater than or equal
        
        boolean sum10 = (a != b);
        System.out.println(sum10); // Not equal
    }
}
