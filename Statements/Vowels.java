class Vowels{
	public static void main(String[] args){
		
		System.out.println("Vowels of Engish");
		char vowels='a';
		
		switch (vowels){
			case 'a':
			System.out.println("A is the vowels");
			break;
			
			case 'e':
			System.out.println("E is the vowels");
			break;
			
			case 'i':
			System.out.println("I is the vowels");
			break;
			
			case 'o':
			System.out.println("O is the vowels");
			break;
			
			case 'u':
			System.out.println("U is the vowels");
			break;
			
			default :
			System.out.println("they are not vowels");
		}
	}
}
			